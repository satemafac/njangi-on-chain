def scene_html(c: dict, words: list[dict], idx: int) -> tuple[str, str]:
    """Return (markup, timing css) for one clip scene."""
    sid = f"s{idx}"
    spans = []
    css = []
    for j, w in enumerate(words):
        cls = "k" if w["w"].strip(".,\"'?!").lower() in set(c.get("keywords", [])) else ""
        spans.append(f'<span id="{sid}w{j}" class="{cls}">{html.escape(w["w"])}</span>')
        # word lights up at t and stays lit until the scene ends
        css.append(f"#{sid}w{j}{{animation-name:{sid}w{j}}} @keyframes {sid}w{j}{{0%,{pct(w['t'])}%{{color:#3a362f}} {pct(w['t'] + 0.001)}%,100%{{color:{'var(--gold)' if cls else 'var(--cream)'}}}}}")
    visual = c.get("visual", "quote")
    viz = ""
    if visual == "stat":
        viz = f'<div class="viz"><p class="big">{c["stat"]}<small>{html.escape(c["stat_label"])}</small></p></div>'
    elif visual == "fees":
        viz = ('<div class="viz"><div class="bars">'
               '<div class="bar"><span>Europe</span><i style="--w:.125"></i><b>~2%</b></div>'
               '<div class="bar"><span>Africa</span><i style="--w:1"></i><b>up to 16%</b></div>'
               '</div></div>')
    elif visual == "route":
        viz = ('<div class="viz"><svg viewBox="0 0 900 560" role="img" aria-label="Money from Togo travels to a bank in Europe before reaching neighbouring Ghana.">'
               '<path class="direct" d="M 300 430 L 600 430"/>'
               '<path class="route" d="M 300 430 C 300 120, 600 120, 600 430"/>'
               '<circle class="dot" cx="300" cy="430" r="34"/><text class="lbl" x="300" y="510">TOGO</text>'
               '<circle class="dot" cx="600" cy="430" r="34"/><text class="lbl" x="600" y="510">GHANA</text>'
               '<circle class="dot hot" cx="450" cy="200" r="34"/><text class="lbl" x="450" y="150">A BANK IN EUROPE</text>'
               '<circle class="coin" r="14" style="offset-path: path(\'M 300 430 C 300 120, 600 120, 600 430\')"/>'
               '</svg></div>')
        # route draws + coin travels during the clip
        a, b = c["t0"] + 1.0, c["t1"] - 0.6
        css.append(f".{sid} .route{{animation:{sid}route var(--total) linear 1 both}} @keyframes {sid}route{{0%,{pct(a)}%{{stroke-dashoffset:1400}} {pct(b)}%,100%{{stroke-dashoffset:0}}}}")
        css.append(f".{sid} .coin{{animation:{sid}coin var(--total) linear 1 both}} @keyframes {sid}coin{{0%,{pct(a)}%{{offset-distance:0%;opacity:0}} {pct(a + 0.05)}%{{opacity:1}} {pct(b)}%{{offset-distance:100%;opacity:1}} {pct(b + 0.05)}%,100%{{offset-distance:100%;opacity:0}}}}")
    if visual == "fees":
        a, b = c["t0"] + 0.8, c["t1"] - 1.0
        css.append(f".{sid} .bar i::after{{transform:scaleX(0);animation:{sid}bar var(--total) cubic-bezier(.4,0,.2,1) 1 both}} @keyframes {sid}bar{{0%,{pct(a)}%{{transform:scaleX(0)}} {pct(b)}%,100%{{transform:scaleX(var(--w))}}}}")
    if visual == "stat":
        a = c["t0"] + float(c.get("stat_at", 0.8))
        css.append(f".{sid} .big{{opacity:0;transform:translateY(3cqw);animation:{sid}stat var(--total) cubic-bezier(.2,.7,.2,1) 1 both}} @keyframes {sid}stat{{0%,{pct(a)}%{{opacity:0;transform:translateY(3cqw)}} {pct(a + 0.5)}%,100%{{opacity:1;transform:translateY(0)}}}}")
    n = len(words)
    cap_size = "6.4cqw" if n <= 22 else "5.6cqw" if n <= 34 else "4.9cqw"
    markup = (f'<section class="scene {sid}">'
              f'<div><p class="eyebrow">{html.escape(c["eyebrow"])}</p><p class="who">{html.escape(c.get("who", "Farida Nabourema, in her own words"))}</p></div>'
              f'<div class="mid">{viz}<p class="cap" style="font-size:{cap_size}">{" ".join(spans)}</p></div>'
              f'<div class="foot"><span class="mark">Njangi On-Chain</span><span>{html.escape(c.get("foot", "source in comments"))}</span></div>'
              f'</section>')
    # scene visibility window (short fades)
    f = 0.35
    css.append(f".{sid}{{animation-name:{sid}show}} @keyframes {sid}show{{0%,{pct(c['t0'] - f)}%{{opacity:0}} {pct(c['t0'])}%,{pct(c['t1'])}%{{opacity:1}} {pct(c['t1'] + f)}%,100%{{opacity:0}}}}")
    return markup, "\n".join(css)


TOTAL = 1.0


def pct(t: float) -> str:
    return f"{max(0.0, min(100.0, 100.0 * t / TOTAL)):.3f}"


