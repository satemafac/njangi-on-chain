def main() -> int:
    global TOTAL
    ap = argparse.ArgumentParser()
    ap.add_argument("--audio", required=True)
    ap.add_argument("--words", required=True)
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--fps", type=int, default=24)
    ap.add_argument("--no-render", action="store_true")
    a = ap.parse_args()

    spec = json.loads(Path(a.spec).read_text())
    wj = json.loads(Path(a.words).read_text())
    words = [w for s in wj["segments"] for w in s.get("words", [])]
    out = Path(a.out)
    timeline, total = build_audio(Path(a.audio), spec, out)
    TOTAL = total

    scenes, css = [], []
    for i, c in enumerate(timeline):
        m, t = scene_html(c, words_for(c, words), i)
        scenes.append(m)
        css.append(t)
    last_end = timeline[-1]["t1"] + 0.4
    m, t = cards_html(spec["outro_cards"], last_end, total - 0.3, "o")
    scenes.append(m)
    css.append(t)
    if spec.get("intro_cards"):
        m, t = cards_html(spec["intro_cards"], 0.15, spec["intro"] - 0.25, "i")
        scenes.append(m)
        css.append(t)

    page = (TEMPLATE.replace("__TOTAL__", f"{total:.3f}")
            .replace("__SCENES__", "\n".join(scenes))
            .replace("__TIMING__", "\n".join(css)))
    html_path = ROOT / "marketing" / "assets" / f"{spec['name']}.html"
    html_path.write_text(page)
    print(f"html -> {html_path}  total {total:.2f}s")
    for c in timeline:
        print(f"  {c['id']:<8} {c['t0']:6.2f} -> {c['t1']:6.2f}  ({c['dur']:.2f}s)")
    if a.no_render:
        return 0

    frames = out / "frames"
    if frames.exists():
        for f in frames.glob("*.png"):
            f.unlink()
    sh("node", str(HERE / "capture-animation.js"), "--in", str(html_path), "--out", str(frames),
       "--width", "1080", "--height", "1920", "--seconds", f"{total:.3f}", "--fps", str(a.fps))
    mp4 = out / f"{spec['name']}.mp4"
    sh("ffmpeg", "-v", "error", "-y", "-framerate", str(a.fps), "-i", str(frames / "f%04d.png"),
       "-i", str(out / "audio.wav"), "-c:v", "libx264", "-profile:v", "high", "-level", "4.1", "-preset", "slow",
       "-crf", "18", "-pix_fmt", "yuv420p", "-r", str(a.fps), "-c:a", "aac", "-b:a", "160k", "-shortest",
       "-movflags", "+faststart", str(mp4))
    print(f"mp4 -> {mp4}")
    for f in frames.glob("*.png"):
        f.unlink()
    frames.rmdir()
    return 0


