def sh(*cmd: str) -> None:
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if r.returncode != 0:
        sys.exit(f"command failed: {' '.join(cmd)}\n{r.stderr}")


def build_audio(src: Path, spec: dict, out: Path) -> list[dict]:
    """Cut + concat clips. Returns clip list with timeline offsets."""
    out.mkdir(parents=True, exist_ok=True)
    intro, gap, outro = spec["intro"], spec["gap"], spec["outro"]
    parts, timeline, t = [], [], intro
    sil = out / "sil-gap.wav"
    sh("ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=48000:cl=mono", "-t", str(gap), sil)
    intro_f = out / "sil-intro.wav"
    sh("ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=48000:cl=mono", "-t", str(intro), intro_f)
    outro_f = out / "sil-outro.wav"
    sh("ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=48000:cl=mono", "-t", str(outro), outro_f)
    parts.append(intro_f)
    for i, c in enumerate(spec["clips"]):
        dur = c["end"] - c["start"]
        f = out / f"clip-{c['id']}.wav"
        fade = 0.08
        sh("ffmpeg", "-v", "error", "-y", "-ss", str(c["start"]), "-t", str(dur), "-i", str(src),
           "-af", f"afade=t=in:st=0:d={fade},afade=t=out:st={dur - fade}:d={fade},"
                  f"loudnorm=I=-16:TP=-1.5:LRA=11", "-ar", "48000", "-ac", "1", str(f))
        real = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                     "-of", "csv=p=0", str(f)], capture_output=True, text=True).stdout.strip())
        timeline.append({**c, "t0": round(t, 3), "t1": round(t + real, 3), "dur": round(real, 3)})
        parts.append(f)
        t += real
        if i < len(spec["clips"]) - 1:
            parts.append(sil)
            t += gap
    parts.append(outro_f)
    lst = out / "concat.txt"
    lst.write_text("".join(f"file '{p.resolve()}'\n" for p in parts))
    sh("ffmpeg", "-v", "error", "-y", "-f", "concat", "-safe", "0", "-i", str(lst), "-c:a", "pcm_s16le", str(out / "audio.wav"))
    total = t + outro
    (out / "timeline.json").write_text(json.dumps({"total": round(total, 3), "clips": timeline}, indent=2))
    return timeline, total


def words_for(clip: dict, words: list[dict]) -> list[dict]:
    lo, hi = clip["start"] - 0.05, clip["end"] + 0.05
    sel = [w for w in words if lo <= w["start"] and w["end"] <= hi]
    off = clip["t0"] - clip["start"]
    return [{"w": w["word"].strip(), "t": round(w["start"] + off, 3), "d": round(max(0.12, w["end"] - w["start"]), 3)} for w in sel]


