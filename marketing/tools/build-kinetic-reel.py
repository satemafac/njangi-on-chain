#!/usr/bin/env python3
"""
build-kinetic-reel.py — assemble a 9:16 "voice + kinetic type" Reel from
interview audio clips and a Whisper word-timestamp JSON.

Pipeline:
  1. Cut each clip from the source audio (short fades), concatenate with gaps
     and an intro/outro of silence -> audio.wav. Records where every clip lands
     on the final timeline.
  2. Pull the words that fall inside each clip from the Whisper JSON, shift
     them onto the timeline, and emit them as spans with CSS animation delays
     so the caption "lights up" word by word as she speaks.
  3. Write the HTML (template lives in this file), render frames with
     capture-animation.js (WAAPI seek => deterministic), mux with the audio.

Usage:
  python3 marketing/tools/build-kinetic-reel.py \
      --audio  scratch/farida/segment.wav \
      --words  scratch/farida/segment.words.json \
      --spec   marketing/assets/poverty-tax-reel.spec.json \
      --out    marketing/assets/export/poverty-tax-reel \
      [--fps 24] [--no-render]

The spec is JSON: {"intro": 1.6, "gap": 0.55, "outro": 13.0, "clips": [
  {"id":"tax","start":435.2,"end":443.4,"eyebrow":"...", "visual":"quote"|"stat"|"route"|"fees", ...}
]}. Times are seconds within --audio.
"""
